"""Предложенные области парковок (`tiles`) для cameras.yml.

ВЛАДЕЛЕЦ cameras.yml — агент A2, поэтому я его не правлю. Здесь лежат
прямоугольники, снятые по эталонным кадрам refs/*.jpg и использованные для
замеров в docs/BENCH.md и docs/DETECTION_QUALITY.md. Их нужно перенести
в `tiles:` соответствующих камер — целиком или уточнив под финальную разметку
spots/zones.

Правило нарезки: регион выгоднее делать близким к 640x640. Регион 640x240
после letterbox всё равно считается как полный тайл 640x640, то есть узкая
полоса стоит столько же, сколько квадрат, но полезной площади в ней втрое
ме��ьше. Лучше расширить регион по вертикали, чем добавить второй.

Координаты — в системе эталонного кадра камеры (frame_size из cameras.yml).
"""

from __future__ import annotations

# cam_id -> список [x1, y1, x2, y2]
PROPOSED_TILES: dict[str, list[list[int]]] = {
    # 1920x1080. Карман внизу слева (авто 50-70 px) + ряд у павильонов сверху (~35 px).
    "CAM-001": [
        [0, 440, 768, 1080],    # карман внизу слева, самая плотная стоянка; 2 тайла
        [620, 180, 1260, 420],  # ряд у павильонов сверху, мелкие авто; 1 тайл
    ],
    # 1920x1080. Худшая камера: авто 25-45 px, перекрытия стройкой и деревьями.
    "CAM-002": [
        [900, 440, 1540, 1080],  # карман вдоль Светланской + стоянка у ТЦ; 1 тайл
        [1380, 390, 1920, 700],  # верхняя площадка справа; 1 тайл
    ],
    # 2592x1944. Лучшая камера, но и самая дорогая по площади.
    "CAM-003": [
        [1230, 810, 2540, 1090],  # размеченный паркинг перед ТЦ, авто 80-120 px; 3 тайла
        [1700, 1250, 2490, 1470],  # ряд внизу справа, авто 90-110 px; 2 тайла
        [295, 565, 1105, 950],     # грунтовые ряды слева вверху, авто 40-55 px; 2 тайла
    ],
}


def as_yaml_snippet() -> str:
    """Готовый фрагмент для вставки в cameras.yml."""
    lines: list[str] = []
    for cam_id, rects in PROPOSED_TILES.items():
        lines.append(f"# {cam_id}")
        lines.append("    tiles:")
        for r in rects:
            lines.append(f"      - {r}")
    return "\n".join(lines)


def apply_to_config(config, only_if_empty: bool = True) -> list[str]:
    """Подставить предложенные tiles в загруженный Config (в памяти, не в файл).

    Нужно замерам: пока A2 не заполнил cameras.yml, bench и оценка качества
    иначе тайлили бы весь кадр и мерили не то, что поедет в прод.
    Возвращает список камер, которым tiles проставлены.
    """
    touched: list[str] = []
    for cam in config.cameras:
        rects = PROPOSED_TILES.get(cam.id)
        if not rects:
            continue
        if cam.tiles and only_if_empty:
            continue
        w, h = cam.frame_size
        cam.tiles = [
            (max(0, x1), max(0, y1), min(w, x2), min(h, y2)) for x1, y1, x2, y2 in rects
        ]
        touched.append(cam.id)
    return touched
